#!/usr/bin/env node
/**
 * Builds data/map-na.js: the Oyster Passport map (Build Sheet 5.5).
 * US states and Canadian provinces from Natural Earth admin-1, 1:50m
 * (public domain), projected (Albers, centred on the US) and simplified.
 * Alaska, Hawaii and the far north are left out: no oysters there.
 *
 * Not part of the site; run by hand when the map needs rebuilding.
 * Terminal, in a scratch folder:
 *   npm i d3-geo@2 mapshaper@0.6
 *   (get ne_50m_admin_1_states_provinces.geojson from
 *    github.com/nvkelso/natural-earth-vector, folder geojson/)
 *   node <repo>/tools/build-map-na.js ne_50m_admin_1_states_provinces.geojson <repo>/data/map-na.js
 * Needs Node 18+. Writes one file; prints its size.
 */
'use strict';
const fs = require('fs');
const path = require('path');
// The packages are installed in the folder you run this from.
const req = require('module').createRequire(path.join(process.cwd(), 'noop.js'));
const d3 = req('d3-geo');
const mapshaper = req('mapshaper');

const [src, out] = process.argv.slice(2);
if (!src || !out) { console.error('Usage: node build-map-na.js <ne_50m_admin_1.geojson> <out map-na.js>'); process.exit(1); }

// Natural Earth postal code -> the code used in data/regions.js (where they differ).
const CODE = { PE: 'pei' };
const BOX = [-127.5, 24.3, -59.5, 51.5];      // lon/lat shown: lower 48, southern Canada
const W = 900, H = 520;
const INSET_BOX = [-82.5, 31.8, -59.5, 47.8]; // East Coast inset

(async () => {
  const all = JSON.parse(fs.readFileSync(src, 'utf8'));
  const keep = all.features.filter((f) => ['USA', 'CAN'].includes(f.properties.adm0_a3) && !['AK', 'HI'].includes(f.properties.postal));
  const slim = { type: 'FeatureCollection', features: keep.map((f) => ({
    type: 'Feature', properties: { code: (CODE[f.properties.postal] || f.properties.postal).toLowerCase(), name: f.properties.name, country: f.properties.adm0_a3 }, geometry: f.geometry,
  })) };
  // Simplify (keeps shared borders shared), then clip to the box.
  const r = await mapshaper.applyCommands(
    `-i in.json -clip bbox=${BOX.join(',')} -simplify 18% keep-shapes -filter-slivers min-area=25km2 -o out.json format=geojson`,
    { 'in.json': JSON.stringify(slim) });
  const geo = JSON.parse(r['out.json']);
  // GeoJSON rings run counter-clockwise; d3 reads them as the rest of the
  // globe unless they run clockwise. Reverse every ring.
  geo.features.forEach((f) => {
    if (!f.geometry) return;
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    polys.forEach((poly) => poly.forEach((ring) => ring.reverse()));
  });
  const proj = d3.geoAlbers().rotate([96, 0]).center([0, 38.5]).parallels([29.5, 45.5]).fitExtent([[6, 6], [W - 6, H - 6]], geo);
  const geoPath = d3.geoPath(proj);
  const p = (f) => (geoPath(f) || '').replace(/-?\d+\.?\d*(e-?\d+)?/g, (n) => String(Math.round(Number(n))));
  p.centroid = (f) => geoPath.centroid(f);
  const shapes = geo.features.filter((f) => f.geometry).map((f) => {
    const c = p.centroid(f);
    return { code: f.properties.code, name: f.properties.name, country: f.properties.country === 'CAN' ? 'CA' : 'US', d: p(f), x: Math.round(c[0]), y: Math.round(c[1]) };
  }).sort((a, b) => (a.code < b.code ? -1 : 1));
  // Clip by the map's own frame, so the box is the visible area.
  const ib = [proj([INSET_BOX[0], INSET_BOX[3]]), proj([INSET_BOX[2], INSET_BOX[3]]), proj([INSET_BOX[0], INSET_BOX[1]]), proj([INSET_BOX[2], INSET_BOX[1]])];
  const xs = ib.map((q) => q[0]), ys = ib.map((q) => q[1]);
  const inset = [Math.floor(Math.min(...xs)), Math.floor(Math.min(...ys)), Math.ceil(Math.max(...xs) - Math.min(...xs)), Math.ceil(Math.max(...ys) - Math.min(...ys))];
  const body = '/*\n * Generated by tools/build-map-na.js — do not edit by hand.\n' +
    ' * US states and Canadian provinces, Natural Earth admin-1 1:50m (public domain),\n' +
    ' * Albers projection, simplified. Global HS_MAP_NA:\n' +
    ' *   viewBox  the whole map, "0 0 W H"\n' +
    ' *   inset    the East Coast, [x, y, w, h] in the same coordinates\n' +
    ' *   shapes   [{ code (data/regions.js style), name, country, d (SVG path), x, y (label point) }]\n */\n' +
    '(function (root) {\n  \'use strict\';\n  root.HS_MAP_NA = ' + JSON.stringify({ viewBox: `0 0 ${W} ${H}`, inset, shapes }) +
    ';\n  if (typeof module !== \'undefined\' && module.exports) module.exports = root.HS_MAP_NA;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
  fs.writeFileSync(out, body);
  console.log(`${path.basename(out)}: ${shapes.length} shapes, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB`);
})().catch((e) => { console.error(e); process.exit(1); });
